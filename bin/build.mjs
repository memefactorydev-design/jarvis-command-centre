#!/usr/bin/env node
// Build public/index.html and the live assistant's knowledge (api/_lib/roster-context.js).
//
//   npm run build            uses data/roster.json, or the demo roster if you haven't scanned yet
//   npm run build -- --demo  force the demo roster
//
// Inputs:  web/template.html · data/roster.json (or data/example-roster.json) · jarvis.config.json · voice manifest
// Outputs: public/index.html · public/assets/** · public/voice/** · api/_lib/roster-context.js
import fs from "node:fs";
import path from "node:path";
import { P, loadConfig, readJSON, stamp, assistantDotted, log } from "./lib/common.mjs";

const args = process.argv.slice(2);

function plain(x) { return String(x || "").replace(/<[^>]+>/g, "").replace(/`/g, "").trim(); }

export function loadRoster({ forceDemo = false } = {}) {
  const real = forceDemo ? null : readJSON(P.data, null);
  if (real && Array.isArray(real.depts)) return real;
  const demo = readJSON(P.example, null);
  if (!demo) throw new Error("data/example-roster.json is missing");
  demo.demo = true;
  return demo;
}

export function loadVoiceManifest(roster) {
  const own = readJSON(path.join(P.voice, "manifest.json"), null);
  if (!roster.demo && own) return { dir: P.voice, manifest: own };
  if (roster.demo) {
    const demo = readJSON(path.join(P.demoVoice, "manifest.json"), null);
    if (demo) return { dir: P.demoVoice, manifest: demo };
  }
  return { dir: null, manifest: own && roster.demo ? { clips: {} } : (own || { clips: {} }) };
}

function rosterText(data, cfg) {
  const counts = { live: 0, testing: 0, blocked: 0 };
  for (const d of data.depts) for (const a of d.agents) counts[a.status] = (counts[a.status] || 0) + 1;
  const total = counts.live + counts.testing + counts.blocked;
  const L = [];
  L.push(`ORGANISATION: ${cfg.orgName}. OWNER: ${cfg.owner.name} (${cfg.owner.label}).`);
  L.push(`TOTAL: ${total} agents — ${counts.live} live, ${counts.testing} testing, ${counts.blocked} blocked.`);
  if ((data.team || []).length) L.push("PEOPLE: " + data.team.map((t) => `${t.name} (${t.role})`).join("; "));
  for (const d of data.depts) {
    L.push("");
    L.push(`## DEPARTMENT: ${d.name} — ${d.blurb || ""} (${d.agents.length} agents${d.who ? `; ${d.who}` : ""})`);
    if (d.note) L.push("Note: " + plain(d.note));
    for (const a of d.agents) {
      L.push(`- ${a.name} [${String(a.status).toUpperCase()}] (${a.tag || ""}). Job: ${plain(a.job)}`);
      L.push("  Trigger: " + (a.trigger || []).map(([k, v]) => `${k}: ${v}`).join("; "));
      if ((a.connects || []).length) L.push("  Connects: " + a.connects.map(plain).join("; "));
      L.push(`  Model: ${a.model || ""}. Status note: ${plain(a.statusNote)}`);
      if ((a.waiting || []).length) L.push(`  ${a.waitingLabel || "Waiting on"}: ` + a.waiting.map(plain).join("; "));
      if ((a.handoff || []).length) L.push("  Hands off: " + a.handoff.map(plain).join("; "));
      if ((a.skills || []).length) L.push("  Skills/commands: " + a.skills.join(", "));
      L.push(`  Location: ${a.path || ""}`);
    }
  }
  if ((data.sched || []).length) {
    L.push("", "## SCHEDULES (when | task | runner | state)");
    for (const r of data.sched) L.push(r.join(" | "));
  }
  if ((data.planned || []).length) L.push("", "## PLANNED, NOT YET BUILT: " + data.planned.map(([a, b]) => `${a} ${b}`).join("; "));
  return L.join("\n");
}

function copyDir(src, dst, filter = () => true) {
  if (!src || !fs.existsSync(src)) return 0;
  fs.mkdirSync(dst, { recursive: true });
  let n = 0;
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (e.name.startsWith(".")) continue;
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) n += copyDir(s, d, filter);
    else if (filter(e.name)) {
      const ss = fs.statSync(s);
      let same = false;
      try { const ds = fs.statSync(d); same = ds.size === ss.size && ds.mtimeMs >= ss.mtimeMs; } catch {}
      if (!same) fs.copyFileSync(s, d);
      n++;
    }
  }
  return n;
}

export function build({ quiet = false, forceDemo = false } = {}) {
  const data = loadRoster({ forceDemo });
  const cfg = loadConfig(data);
  const { dir: voiceDir, manifest } = loadVoiceManifest(data);
  const built = stamp();
  const ver = "?v=" + built.replace(/\D/g, "");
  for (const d of data.depts) delete d._c;

  // 1. live assistant knowledge
  const text = rosterText(data, cfg);
  const js = "// GENERATED by bin/build.mjs from your roster — do not edit by hand.\n" +
    `export const ROSTER_TEXT = ${JSON.stringify(text)};\n` +
    `export const BUILT = ${JSON.stringify(built)};\n` +
    `export const ASSISTANT = ${JSON.stringify(cfg.assistantName)};\n` +
    `export const HONORIFIC = ${JSON.stringify(cfg.honorific)};\n` +
    `export const OWNER = ${JSON.stringify(cfg.owner.name)};\n` +
    `export const ORG = ${JSON.stringify(cfg.orgName)};\n` +
    `export const MODEL = ${JSON.stringify(cfg.model)};\n` +
    `export const VOICE_ID = ${JSON.stringify(cfg.voiceId)};\n` +
    `export const TTS_MODEL = ${JSON.stringify(cfg.ttsModel)};\n`;
  fs.mkdirSync(path.dirname(P.ctx), { recursive: true });
  fs.writeFileSync(P.ctx, js);

  // 2. page
  const counts = { all: 0, live: 0, testing: 0, blocked: 0 };
  for (const d of data.depts) for (const a of d.agents) { counts.all++; counts[a.status]++; }
  const sources = (data.sources || []).join(", ") || (data.demo ? "demo roster" : "your agents folder");
  const footer = data.demo
    ? `This is the <b>demo roster</b> of a fictional company. Run <code>npm run setup</code> (or <code>/jarvis-setup</code> in Claude Code) to point ${cfg.assistantName} at your own agents folder.`
    : `Built ${built} from <code>${sources}</code> by <code>npm run build</code>. The scanner re-reads your agents folder every ${cfg.autoRescanHours} hours while the server runs; new agents appear automatically and vanished ones are dropped. Cards edited by you or by <code>/jarvis-scan</code> are never overwritten.`;
  const manifestForPage = { voice_name: manifest.voice_name || cfg.voiceName, generated: manifest.generated || "", clips: manifest.clips || {} };
  let html = fs.readFileSync(P.template, "utf8");
  const rep = {
    __ASSISTANT_DOTTED__: assistantDotted(cfg.assistantName),
    __ASSISTANT__: cfg.assistantName,
    __HONORIFIC__: cfg.honorific,
    __ORG_NAME__: cfg.orgName,
    __OWNER_LABEL__: cfg.owner.label,
    __OWNER_NAME__: cfg.owner.name,
    __OWNER_LINE__: cfg.owner.line,
    __TAGLINE__: cfg.tagline || "",
    __FOOTER__: footer,
    __BUILD_STAMP__: built,
    __LAST_SCAN__: data.last_scan || (data.demo ? "demo" : built.slice(0, 10)),
    __COUNT_LINE__: `${counts.all} agents · ${counts.live} live · ${counts.testing} testing · ${counts.blocked} blocked`,
    __ROSTER_JSON__: JSON.stringify(data).replace(/</g, "\\u003c"),
    __VOICE_JSON__: JSON.stringify(manifestForPage).replace(/</g, "\\u003c"),
    __ASSET_V__: ver,
  };
  for (const [k, v] of Object.entries(rep)) html = html.split(k).join(v);
  // cache-busting: version every static asset reference with the build stamp
  html = html.replace(/((?:assets|voice)\/[\w./-]+\.(?:mp3|mp4|gif|jpg|jpeg|png|webp))(?![\w?])/g, (m) => m + ver);
  fs.mkdirSync(P.public, { recursive: true });
  fs.writeFileSync(path.join(P.public, "index.html"), html);

  // 3. static assets + voice clips
  const nAssets = copyDir(P.assets, path.join(P.public, "assets"));
  fs.rmSync(path.join(P.public, "voice"), { recursive: true, force: true });
  const nClips = voiceDir ? copyDir(voiceDir, path.join(P.public, "voice"), (f) => f.endsWith(".mp3")) : 0;

  if (!quiet) log(`Built public/index.html · ${counts.all} agents (${counts.live} live, ${counts.testing} testing, ${counts.blocked} blocked)${data.demo ? " · DEMO roster" : ""} · ${nAssets} assets · ${nClips} voice clips · knowledge ${Math.round(text.length / 1000)}k chars`);
  return { built, counts, demo: !!data.demo, clips: nClips };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("build.mjs")) {
  try { build({ quiet: args.includes("--quiet"), forceDemo: args.includes("--demo") }); }
  catch (e) { console.error("build failed:", e.message); process.exit(1); }
}
